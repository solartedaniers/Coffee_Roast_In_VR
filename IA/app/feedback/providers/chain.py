import logging
import time
from dataclasses import dataclass

from app.feedback.providers.base import FeedbackProvider, ProviderUnavailable
from app.feedback.text_cleaner import FeedbackTextCleaner

log = logging.getLogger(__name__)


@dataclass(frozen=True)
class GeneratedFeedback:
    text: str
    provider: str


class ProviderChain:
    """Prueba los proveedores en orden hasta obtener un texto útil, sin pasarse del tiempo total."""

    def __init__(self, providers: list[FeedbackProvider], cleaner: FeedbackTextCleaner,
                 total_timeout_seconds: float, clock=time.monotonic):
        self.providers = providers
        self.cleaner = cleaner
        self.total_timeout_seconds = total_timeout_seconds
        self.clock = clock

    def generate(self, prompt: str) -> GeneratedFeedback | None:
        deadline = self.clock() + self.total_timeout_seconds
        for provider in self.providers:
            remaining = deadline - self.clock()
            if remaining <= 0:
                log.warning("Feedback time budget exhausted before trying %s", provider.name)
                break
            try:
                text = self.cleaner.clean(provider.generate(prompt, remaining))
            except ProviderUnavailable as error:
                log.warning("Feedback provider %s failed: %s", provider.name, error)
                continue
            if text:
                log.info("Feedback generated by %s", provider.name)
                return GeneratedFeedback(text, provider.name)
            log.warning("Feedback provider %s returned no usable text", provider.name)
        return None
