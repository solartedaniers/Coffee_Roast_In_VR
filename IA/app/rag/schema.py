"""Crea las tablas del RAG solo si no existen, igual que hacían Spring AI y JPA.

Sobre una base que ya las tiene no cambia nada.
"""
from psycopg import sql

from app.rag.database import Database
from app.rag.ingested_document_repository import INGESTED_DOCUMENTS_TABLE


class RagSchema:
    def __init__(self, database: Database, vector_table: str, dimensions: int):
        self.database = database
        self.vector_table = vector_table
        self.dimensions = dimensions

    def statements(self) -> list[sql.Composable]:
        table = sql.Identifier(self.vector_table)
        return [
            sql.SQL("CREATE EXTENSION IF NOT EXISTS vector"),
            sql.SQL("CREATE EXTENSION IF NOT EXISTS hstore"),
            sql.SQL('CREATE EXTENSION IF NOT EXISTS "uuid-ossp"'),
            sql.SQL("CREATE TABLE IF NOT EXISTS {} (id uuid DEFAULT uuid_generate_v4() PRIMARY KEY, "
                    "content text, metadata json, embedding vector({}))").format(table, sql.Literal(self.dimensions)),
            sql.SQL("CREATE INDEX IF NOT EXISTS {} ON {} USING hnsw (embedding vector_cosine_ops)").format(
                sql.Identifier(f"{self.vector_table}_index"), table),
            sql.SQL("CREATE TABLE IF NOT EXISTS {} (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    "chunk_count integer NOT NULL, content_hash varchar(64) NOT NULL, "
                    "file_name varchar(255) NOT NULL UNIQUE, ingested_at timestamp(6) with time zone NOT NULL)").format(
                sql.Identifier(INGESTED_DOCUMENTS_TABLE)),
        ]

    def ensure(self) -> None:
        with self.database.transaction() as connection:
            for statement in self.statements():
                connection.execute(statement)
