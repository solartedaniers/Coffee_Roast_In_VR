"""Historial de preguntas y respuestas por intento de tueste, en una tabla propia del servicio IA.

user_id no tiene llave foránea a users a propósito: esta tabla no debe depender de las del backend.
No se guarda el audio, solo el texto.
"""
import json
from dataclasses import dataclass
from uuid import UUID

from psycopg import sql

from app.rag.citations import Citation
from app.rag.database import Database
from app.voice.answer.prompt import ConversationTurn
from app.voice.contracts import AnswerStatus

VOICE_EXCHANGES_TABLE = "voice_assistant_exchanges"


@dataclass(frozen=True)
class VoiceExchange:
    user_id: int
    roast_attempt_id: UUID
    question: str | None
    answer: str
    status: AnswerStatus
    citations: list[Citation]
    transcription_provider: str | None
    answer_provider: str | None
    speech_provider: str | None
    latency_millis: int


def history_statements() -> list[sql.Composable]:
    table = sql.Identifier(VOICE_EXCHANGES_TABLE)
    return [
        sql.SQL("CREATE TABLE IF NOT EXISTS {} (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                "user_id bigint NOT NULL, roast_attempt_id uuid NOT NULL, question text, answer text NOT NULL, "
                "status varchar(20) NOT NULL, citations json NOT NULL, transcription_provider varchar(20), "
                "answer_provider varchar(20), speech_provider varchar(20), latency_millis integer NOT NULL, "
                "created_at timestamp(6) with time zone NOT NULL DEFAULT now())").format(table),
        sql.SQL("CREATE INDEX IF NOT EXISTS {} ON {} (user_id, roast_attempt_id, created_at)").format(
            sql.Identifier(f"{VOICE_EXCHANGES_TABLE}_attempt_index"), table),
    ]


class VoiceExchangeRepository:
    def __init__(self, database: Database):
        self.database = database

    def recent_answered(self, user_id: int, roast_attempt_id: UUID, limit: int) -> list[ConversationTurn]:
        """Últimas respuestas dadas en este intento, de la más vieja a la más nueva."""
        if limit <= 0:
            return []
        statement = sql.SQL(
            "SELECT question, answer FROM {} WHERE user_id = %s AND roast_attempt_id = %s AND status = %s "
            "AND question IS NOT NULL ORDER BY created_at DESC, id DESC LIMIT %s"
        ).format(sql.Identifier(VOICE_EXCHANGES_TABLE))
        with self.database.transaction() as connection:
            rows = connection.execute(statement, (user_id, roast_attempt_id, AnswerStatus.ANSWERED.value,
                                                  limit)).fetchall()
        return [ConversationTurn(question, answer) for question, answer in reversed(rows)]

    def save(self, exchange: VoiceExchange) -> None:
        citations = [{"fileName": c.file_name, "pageNumber": c.page_number, "title": c.title}
                     for c in exchange.citations]
        statement = sql.SQL(
            "INSERT INTO {} (user_id, roast_attempt_id, question, answer, status, citations, "
            "transcription_provider, answer_provider, speech_provider, latency_millis) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)"
        ).format(sql.Identifier(VOICE_EXCHANGES_TABLE))
        with self.database.transaction() as connection:
            connection.execute(statement, (
                exchange.user_id, exchange.roast_attempt_id, exchange.question, exchange.answer,
                exchange.status.value, json.dumps(citations, ensure_ascii=False), exchange.transcription_provider,
                exchange.answer_provider, exchange.speech_provider, exchange.latency_millis))
